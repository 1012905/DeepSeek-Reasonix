"use strict";
const { app, BrowserWindow, WebContentsView } = require("electron");
const { listen, wait } = require("./livekit");
(async () => {
  await app.whenReady();
  const page = await listen((_q, res) => { res.writeHead(200, { "Content-Type": "text/html" }); res.end(`<input id=n><button id=go>Go</button>`); });
  const win = new BrowserWindow({ width: 900, height: 600, show: true });
  await win.loadURL("data:text/html," + encodeURIComponent(`<textarea id=compose autofocus></textarea>`));
  win.show(); win.focus(); await wait(600);
  const view = new WebContentsView();
  const c = view.webContents;
  const seen = { beforeInput: 0, inputEvent: 0, focus: 0, mouseDown: 0 };
  c.on("before-input-event", () => seen.beforeInput++);
  c.on("input-event", (_e, ev) => { seen.inputEvent++; if (ev.type === "mouseDown") seen.mouseDown++; });
  c.on("focus", () => seen.focus++);
  c.debugger.attach("1.3");
  win.contentView.addChildView(view);
  view.setBounds({ x: 300, y: 100, width: 500, height: 300 });
  await c.loadURL(page.url);
  await wait(800);
  const snap = (label) => process.stdout.write(`${label}: ${JSON.stringify(seen)} appFocused=${win.webContents.isFocused()} viewFocused=${c.isFocused()}\n`);
  snap("after load");
  win.webContents.focus(); await wait(300); snap("after giving focus back");
  const before = { ...seen };
  await c.debugger.sendCommand("Input.dispatchMouseEvent", { type: "mousePressed", x: 40, y: 20, button: "left", clickCount: 1 });
  await c.debugger.sendCommand("Input.dispatchMouseEvent", { type: "mouseReleased", x: 40, y: 20, button: "left", clickCount: 1 });
  await c.debugger.sendCommand("Input.dispatchKeyEvent", { type: "keyDown", key: "a", text: "a" });
  await wait(300);
  snap("after CDP click+key");
  win.webContents.focus(); await wait(300);
  c.sendInputEvent({ type: "mouseDown", x: 40, y: 20, button: "left", clickCount: 1 });
  c.sendInputEvent({ type: "mouseUp", x: 40, y: 20, button: "left", clickCount: 1 });
  c.sendInputEvent({ type: "keyDown", keyCode: "b" });
  await wait(300);
  snap("after sendInputEvent (a person's input)");
  page.server.close(); app.exit(0);
})();
